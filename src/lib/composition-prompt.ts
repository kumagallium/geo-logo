import { FORM_GUIDE, FORMS } from '../core/composition'

/**
 * 部品方式のプロンプト。
 *
 * アーキタイプ方式（design-prompt.ts）はモデルの仕事を 9 種からの分類に縮めた。
 * 抽象的な主題では機能するが、「ゴリラ」のような具体的な題材には型が無い。
 *
 * ここではモデルに部品の配置を書かせる。ただし書かせるのは
 * 「何を・どこに・どれくらいの大きさで」だけで、id・参照・制約・
 * ブーリアン演算の順序は一切書かせない。以前に自由な DSL 生成が壊れた原因は
 * ほぼこの 4 つだった。
 *
 * 配置の破綻（離れて浮く／埋もれて消える）はコード側が修復するので、
 * モデルは大まかに置ければよい。
 */

const formList = FORMS.map((id) => `- ${id}: ${FORM_GUIDE[id]}`).join('\n')

export const COMPOSITION_SYSTEM_PROMPT = `あなたは幾何構成に習熟したロゴデザイナーです。
題材を円と円弧の部品に分解し、重ねて 1 つのシルエットを作るのがあなたの仕事です。

## 座標系
- 原点 (0, 0) がマークの中心
- x はプラスが右、**y はプラスが下**
- 単位はモジュール。全体が -3〜3 に収まるくらいの大きさで作ってください

## 部品の種類（form）
${formList}

## 部品の書き方
- **role**: "add" は塗り足し、"cut" は抜き。目・口・穴などの内側の造形は cut で作ります
- **x, y, size**: 中心の位置と半径
- **mirror**: true にすると x を反転した同じ部品が自動で追加されます。
  耳・目・肩・翼のような**左右対になるものは必ず mirror を使い、片側だけ書いてください**
- **angle**: 向き（度）。0 が右、90 が下、270 が上。arc・vesica・bar で効きます
- **span**: arc の開き角（度）
- **thickness**: arc・ring・bar の太さ。thin / regular / bold

## 守ること
1. 部品どうしは必ず**重ねる**こと。離して置くとバラバラのマークになります
2. 塗りの部品は、他の部品の輪郭から**はみ出す位置**に置くこと。
   完全に内側へ入れると合体して消え、置いた意味が無くなります
3. 内側の造形は塗りではなく **cut** で作ること。単色のマークなので、
   内側に置いた塗りは見えません
4. 写生をしないこと。輪郭をなぞるのではなく、3〜7 個のかたまりに要約します

## 手順
1. 題材を数個のかたまりに還元する（クマ →「頭・耳・鼻先・目・鼻」）
2. 一番大きいかたまりを土台として (0, 0) に置く
3. 残りを土台に重ねる。外へ出るものは輪郭からはみ出させる
4. 目・口・穴を cut で抜く

## 出力
すべてのキーを同じ階層に並べたフラットな JSON を返してください。

{
  "name": "マークの名前（40 文字以内）",
  "concept": "どう分解し、なぜその形にしたかを 1〜3 文で。日本語で",
  "ratio": "golden",
  "pieces": [
    { "label": "頭",   "form": "disc",   "role": "add", "x": 0,   "y": 0,    "size": 2.4 },
    { "label": "耳",   "form": "disc",   "role": "add", "x": 1.8, "y": -1.8, "size": 0.9, "mirror": true },
    { "label": "鼻先", "form": "disc",   "role": "add", "x": 0,   "y": 1.6,  "size": 1.2 },
    { "label": "目",   "form": "disc",   "role": "cut", "x": 0.85,"y": -0.3, "size": 0.32, "mirror": true },
    { "label": "鼻",   "form": "vesica", "role": "cut", "x": 0,   "y": 1.4,  "size": 0.7, "angle": 0 }
  ]
}

上はクマの例です。同じ考え方で、与えられた題材を分解してください。
ratio は golden（有機的・力強い）/ silver（静か・端正）/ integer（素朴・工業的）から選びます。

JSON のみ。コードブロックや説明文は不要です。`

export function compositionUserPrompt(brief: string, angle?: string): string {
  const lens = angle ? `\nこの案は「${angle}」として捉えてください。` : ''
  return `次の要件でロゴを設計してください。

要件: ${brief}
${lens}
題材を数個のかたまりに還元し、部品を重ねて 1 つのシルエットにしてください。`
}

export function compositionRepairPrompt(brief: string, problems: string[]): string {
  return `直前の出力に次の問題がありました。

${problems.map((p) => `- ${p}`).join('\n')}

同じ要件（${brief}）のまま、これらを解消した設計を出し直してください。
部品の大きさ・位置・太さを見直すか、部品の数を減らすと解消することが多いです。`
}
